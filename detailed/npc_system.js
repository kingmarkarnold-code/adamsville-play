/* initNPCs() — allocates scratch matrices, builds the border, fills spawn
   pools, creates all 1000 NPCs, the 40 render slots, and the 6
   InstancedMeshes (one per body part, unit-box geometry scaled per part).
   Meshes are frustumCulled=false (positions update every frame; culling the
   batch would hide everyone) with cast/receive shadows off for perf. */
function initNPCs(){
  _m1=new THREE.Matrix4(); _m2=new THREE.Matrix4(); _m3=new THREE.Matrix4();
  _m4=new THREE.Matrix4(); _m5=new THREE.Matrix4(); _m6=new THREE.Matrix4();
  _m7=new THREE.Matrix4(); _out=new THREE.Matrix4();
  _col=new THREE.Color();
  buildBorder();
  collectSpots();
  for (var i=0;i<NPC_COUNT;i++) npcs.push(spawnNPC(i));
  for (var s=0;s<MAX_VISIBLE;s++) slots.push(null);
  var unitBox=new THREE.BoxGeometry(1,1,1);
  function im(){
    var m=new THREE.InstancedMesh(unitBox,
      new THREE.MeshLambertMaterial({color:0xffffff}), MAX_VISIBLE);
    m.instanceMatrix.setUsage(THREE.DynamicDrawUsage);
    m.frustumCulled=false;      // positions update every frame; never cull the batch
    m.castShadow=false; m.receiveShadow=false;
    m.count=0; scene.add(m); return m;
  }
  _mesh={ torso:im(), head:im(), armL:im(), armR:im(), legL:im(), legR:im() };
  npcReady=true;
  publishReport();
}

/* tryInit() — waits for the main script's world (THREE, scene,
   roadDrawData) to exist, then inits once. ~20s grace (40 × 500ms); after
   that the NPC system stays off and the game is unaffected. */
var initTries=0;
function tryInit(){
  try{
    if (typeof THREE==='undefined' || typeof scene==='undefined' ||
        typeof roadDrawData==='undefined' || !roadDrawData || !roadDrawData.length){
      if (++initTries<40) setTimeout(tryInit,500);   // ~20s grace
      return;
    }
    initNPCs();
  }catch(e){ /* NPC system stays off; game unaffected */ }
}

