/* updateNPCs(dt, playerPos) — frame tick (wired by the build agent into
   animate()): AI for all 1000 NPCs always runs (data-only), slots refresh
   every 0.5s, bodies render, Report publishes every 5s. When the player is
   driving, the streaming center follows the CAR, not the player on foot.
   dt clamped to 50ms. Never throws. */
function updateNPCs(dt, playerPos){
  if (!npcReady) return;
  try{
    dt=Math.min(0.05, dt||0.016);
    npcTick++;
    var px, pz;
    if (playerPos && isFinite(playerPos.x)){ px=playerPos.x; pz=playerPos.z; }
    else if (typeof player!=='undefined' && player){ px=player.x; pz=player.z; }
    else return;
    try{ if (typeof car!=='undefined' && car && car.driving){ px=car.x; pz=car.z; } }catch(e){}
    var i;
    try{ npcFaceTick(dt,px,pz); }catch(e){}   // v1.14: NPCs turn to face a nearby player
    for (i=0;i<npcs.length;i++) aiNPC(npcs[i],dt);   // data-only, always runs
    streamT-=dt;
    if (streamT<=0){ streamT=0.5; refreshSlots(px,pz); }
    renderNPCs(dt,px,pz);
    repT-=dt;
    if (repT<=0){ repT=5; publishReport(); }
  }catch(e){}
}
