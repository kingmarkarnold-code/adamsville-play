#!/usr/bin/env python3
"""
Adamsville Building Editor 1.6.1 — GAME ZONE DATA LAYER (new in 1.6.0).

WHY THIS MODULE EXISTS
----------------------
Up to 1.5.2 the building editor read and wrote its OWN files
(buildings.json / subdivisions.json / zones.json) in the retired
adamsville-map-editor repo, in an editor-only format the game never
loaded. Joshua's ONE-REPO decision (2026-10-16) makes the game repo
kingmarkarnold-code/adamsville-play the single source of truth, so
1.6.0 works directly on the game's converted per-zone building files:

    detailed/zones/<zone>/buildings.json        (box array, see below)
    detailed/zones/<zone>/buildings_detail.json (index-aligned detail)
    detailed/zones/<zone>/buildings.js         (JS twin of the boxes)
    detailed/zones/<zone>/hero_buildings.json   (special buildings)
    detailed/zones/<zone>/zone.json             (bounds / names)
    detailed/zones/<zone>/roads.json            (reference backdrop)

CONVERTED FORMATS (written by full-build/convert.js, 2026-10-16)
----------------------------------------------------------------
buildings.json = {"version": str, "realCount": int,
                  "buildings": [[x, z, w, d, h, type], ...]}
    Axis-aligned boxes: centre x/z, width, depth, height, numeric
    type code (see TYPE_CODE_MAP below).
buildings_detail.json = [ {"name": str|null, "osm_type": str,
                           "height_m": number,
                           "ring": [[x, z], ...], "moved": number}, ... ]
    Index-aligned with buildings.json: detail[i] describes box[i].
    "ring" is the true footprint polygon. "moved" is conversion
    provenance (0 = unmoved; otherwise how far the conversion moved
    the building off a road) — the editor PRESERVES it and never
    resets it for existing buildings; editor-placed buildings get 0.
buildings.js twin (verified against zones/adamsville/buildings.js):
    /* header comment */
    var OSM_BLDG_VERSION = "<same version string>";
    var OSM_REAL_COUNT = <realCount>;
    var OSM_BUILDINGS = [[...], ...];
    Regenerated by buildings_js_bytes() in exactly that shape.

TYPE-CODE MAPPING (documented per the 1.6.0 brief)
--------------------------------------------------
Derived by cross-tabulating box type codes against detail osm_type
across all seven converted zones (2026-10-16 data):
    code 0 — residential / generic: osm house (most), yes, detached,
             terrace, residential
    code 1 — commercial: osm retail, commercial, warehouse,
             industrial, office
    code 2 — multi-unit / institutional: osm apartments, school,
             church, civic, university
    code 3 — other / special: osm roof, garage, shed, hangar,
             parking, hotel, service, ...
Editor placement maps its building-type names onto (code, osm_type)
via EDITOR_TYPE_MAP below, so a placed building's box code and its
detail osm_type always agree with the converter's scheme.

VERSION CONVENTION (cache-busting)
----------------------------------
The game's cache keys off buildings.json "version" (mirrored into
buildings.js as OSM_BLDG_VERSION), so ANY content change must change
it. On save, a dirty zone's version becomes
    "<YYYY.MM.DD>-building-editor-1.6.1-<zone>"
using the save date. realCount is rewritten to len(buildings).

SAVE = ONE ROUND TRIP (Joshua's standing rule for ALL editors)
--------------------------------------------------------------
round_trip_save():
    1. LOCAL stage — every dirty payload is written to the local
       cache first; failure -> "local-save-failed: <error>".
    2. PUSH leg — ONE GitHub connection pushes every dirty target
       (per dirty zone: buildings.json + buildings_detail.json +
       buildings.js together; plus the editor's subdivisions file
       when dirty). Failure -> "Push to GitHub failed: <error>".
    3. The push connection is CLOSED, a FRESH connection is opened,
       and every pushed file is RE-DOWNLOADED (proof leg). Failure ->
       "push reached GitHub but downloading the proof copy back
       failed: <error> — your save DID reach GitHub" (never claims
       the save missed GitHub when the push landed).
    4. Only on full success is the in-memory view refreshed FROM THE
       RE-DOWNLOADED BYTES and dirty flags cleared. Local edits are
       never discarded on any failure, and the view is never
       reloaded over unsaved edits.
Open+save with no edits performs ZERO pushes (no dirty targets).

FLAGGED BUILDINGS
-----------------
The conversion left 1,532 buildings intersecting roads
(FULL-BUILD-STATS.json "flaggedAll"). Joshua's decision on them is
PENDING, so they are bundled in flagged_buildings.json (alongside
this module), displayed FLAGGED, and LOCKED against move / resize /
delete in this version. Matching: same zone, ring centroid within
FLAG_MATCH_TOLERANCE (1.0 game units) of the flagged centroid.

TRANSPORT INJECTION
-------------------
All GitHub access goes through callables (fetch_file / push_targets /
open_connection) defaulting to this app's github_sync module (suite
1.7.8 connection legs, Contents API — never raw.githubusercontent).
Tests stub those callables; no token ever lives in this module.

Joshua's rule: all code commented.
"""

