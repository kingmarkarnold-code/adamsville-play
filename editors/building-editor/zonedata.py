class FlaggedIndex:
    """
    The bundled flagged-buildings index (flagged_buildings.json):
    {zone: [{"name", "type", "centroid": [x, z], "nearestRoad"}]}.
    A building is flagged when a same-zone entry's centroid is within
    FLAG_MATCH_TOLERANCE of the building's ring centroid.
    """

    def __init__(self, zones_map=None):
        """zones_map: {zone: [entry, ...]} (empty index if None).
        Entries are also bucketed by rounded centroid so match() stays
        fast against zones with tens of thousands of buildings."""
        self.zones = zones_map or {}
        self._buckets = {}
        for zone, entries in self.zones.items():
            bucket = {}
            for e in entries:
                key = (round(e["centroid"][0]),
                       round(e["centroid"][1]))
                bucket.setdefault(key, []).append(e)
            self._buckets[zone] = bucket

    @classmethod
    def load(cls, path=None):
        """Load the bundled index; a missing file means an empty index
        (editor still works, nothing is locked — the .deb always ships
        the file, so this is only a development fallback)."""
        p = Path(path) if path else FLAGGED_FILE
        try:
            raw = json.loads(p.read_text())
            return cls(raw.get("zones", {}))
        except Exception:
            return cls({})

    def match(self, zone, ring):
        """Return the flagged entry matching this ring, or None."""
        entries = self.zones.get(zone) or []
        if not entries:
            return None
        cx, cz = ring_centroid(ring)
        # Only the 3x3 bucket neighbourhood around the centroid can
        # contain a centroid within the tolerance — check just those.
        bucket = self._buckets.get(zone) or {}
        candidates = []
        for bx in (round(cx) - 1, round(cx), round(cx) + 1):
            for bz in (round(cz) - 1, round(cz), round(cz) + 1):
                candidates.extend(bucket.get((bx, bz), []))
        for e in candidates:
            ex, ez = e["centroid"]
            if math.hypot(cx - ex, cz - ez) <= FLAG_MATCH_TOLERANCE:
                return e
        return None

    def count(self, zone=None):
        """Flagged entries for one zone, or the grand total."""
        if zone is not None:
            return len(self.zones.get(zone) or [])
        return sum(len(v) for v in self.zones.values())


