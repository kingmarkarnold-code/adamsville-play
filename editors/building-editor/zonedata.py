# ---------------------------------------------------------------------------
# Geometry helpers (pure, shared by placement / flagged matching / bake)
# ---------------------------------------------------------------------------

def rectangle_ring(x, z, w, d):
    """
    Footprint ring for an axis-aligned box, in the converter's style:
    converter rings start at one corner and walk the perimeter,
    repeating the first point at the end (verified in converted
    buildings_detail.json, e.g. the 5-point rectangle rings). Editor
    rings follow the same convention: start at the min-x/min-z
    corner, go counterclockwise in x/z plane, close the ring.
    """
    hw, hd = w / 2.0, d / 2.0
    return [[x - hw, z - hd], [x + hw, z - hd], [x + hw, z + hd],
            [x - hw, z + hd], [x - hw, z - hd]]


def ring_centroid(ring):
    """Mean of the ring's distinct vertices (centre of the footprint)."""
    pts = ring[:-1] if len(ring) > 1 and ring[0] == ring[-1] else ring
    if not pts:
        return (0.0, 0.0)
    return (sum(p[0] for p in pts) / len(pts),
            sum(p[1] for p in pts) / len(pts))


def point_in_polygon(x, z, polygon):
    """Ray-casting point-in-polygon (used by the subdivision bake)."""
    inside = False
    n = len(polygon)
    for i in range(n):
        x1, z1 = polygon[i]
        x2, z2 = polygon[(i + 1) % n]
        if (z1 > z) != (z2 > z):
            xin = (x2 - x1) * (z - z1) / (z2 - z1) + x1
            if x < xin:
                inside = not inside
    return inside


